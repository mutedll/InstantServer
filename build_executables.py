def generate_macos_codesign_script(manifest: PackagingManifest) -> str:
    return f"""#!/usr/bin/env bash
# Instant Server — macOS Gatekeeper Ad-Hoc Codesigning & DMG Packaging Script
set -euo pipefail

APP_PATH="dist/{manifest.app_name}.app"

if [[ ! -d "$APP_PATH" ]]; then
    echo "Error: $APP_PATH not found. Run PyInstaller first: pyinstaller InstantServer.spec"
    exit 1
fi

echo "[macOS Packager] Clearing quarantine attributes and applying ad-hoc codesign..."
xattr -cr "$APP_PATH" || true
codesign --force --deep --sign - "$APP_PATH"
codesign --verify --verbose=2 "$APP_PATH"

echo "[macOS Packager] Creating compressed InstantServer-macOS.dmg..."
hdiutil create -volname "{manifest.display_name}" \
    -srcfolder "$APP_PATH" \
    -ov -format UDZO \
    "dist/{manifest.app_name}-macOS.dmg"

rm -rf "dist/{manifest.app_name}.app" "dist/{manifest.app_name}" || true
echo "[macOS Packager] Done: dist/{manifest.app_name}-macOS.dmg"
"""

def generate_linux_appimage_wrapper(manifest: PackagingManifest) -> Dict[str, str]:
    apprun = f"""#!/usr/bin/env bash
# Instant Server — Linux AppDir Entrypoint (FUSE2/FUSE3 Resilient)
set -euo pipefail
HERE="$(dirname "$(readlink -f "${{0}}")")"
export APPIMAGE_EXTRACT_AND_RUN=1
export PATH="${{HERE}}/usr/bin:${{PATH}}"

if [[ $# -eq 0 ]]; then
    exec "${{HERE}}/usr/bin/{manifest.app_name}-Linux" --gui
else
    exec "${{HERE}}/usr/bin/{manifest.app_name}-Linux" "$@"
fi
"""

    desktop_entry = f"""[Desktop Entry]
Type=Application
Name={manifest.display_name}
GenericName=Headless Ubuntu Server USB Creator
Comment=Turn any old laptop into a headless Ubuntu Server with Cockpit & CasaOS
Exec=env APPIMAGE_EXTRACT_AND_RUN=1 {manifest.app_name}-Linux --gui
Icon=instant-server
Terminal=false
Categories=System;Utility;
Keywords=Ubuntu;Server;USB;Homelab;CasaOS;Cockpit;
"""
    return {
        "AppRun": apprun,
        "instant-server.desktop": desktop_entry,
    }

